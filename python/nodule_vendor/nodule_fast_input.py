"""Exact shared-plane sampling and native INT16 -> lowered UINT8 packing.

No changed HU window, interpolation, rounding, graph or candidate threshold.
Native packing writes either CHW for ARM or HWC8 directly into PL input CMA.
"""
import ctypes
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import time
import numpy as np
from scipy import ndimage as ndi

_DLLS=[]


class SharedPlaneSampler:
    """Resample the union's bounding rectangle once per native context plane.

    Same integer global-grid coordinates and SciPy float32 interpolation as
    sample_patch_reuse. Mixing, rint and INT16 conversion happen once per plane,
    rather than repeatedly over overlapping tile halos. Setup is timed by caller.
    """
    def __init__(self,hu,spacing,jobs,config):
        spacing=np.asarray(spacing,float)
        if not jobs or spacing.shape!=(3,) or (spacing<=0).any() or not np.isfinite(spacing).all():
            raise ValueError('Need one nonempty plane and valid spacing')
        zm=float(jobs[0][0]);self.config=config
        if any(float(j[0])!=zm or int(j[1])!=j[1] or int(j[2])!=j[2] for j in jobs):
            raise ValueError('Mixed planes or fractional tile grid')
        self.jobs={tuple(j) for j in jobs}
        self.y0=int(min(j[1] for j in jobs));self.x0=int(min(j[2] for j in jobs))
        y1=int(max(j[1] for j in jobs))+config.patch;x1=int(max(j[2] for j in jobs))+config.patch
        y=(self.y0+np.arange(y1-self.y0))*config.xy_mm/spacing[1]
        x=(self.x0+np.arange(x1-self.x0))*config.xy_mm/spacing[2]
        grid=np.meshgrid(y,x,indexing='ij');planes={};context=[]
        for offset in config.context_mm:
            z=np.clip((zm+offset)/spacing[0],0,len(hu)-1);lo,hi=int(np.floor(z)),int(np.ceil(z));alpha=z-lo
            for index in {lo,hi}:
                if index not in planes:
                    planes[index]=ndi.map_coordinates(np.asarray(hu[index],np.float32),grid,
                        order=1,mode='constant',cval=-1000,prefilter=False)
            a=planes[lo]
            if hi!=lo:a=a*(1-alpha)+planes[hi]*alpha
            context.append(np.rint(a).clip(-32768,32767).astype(np.int16))
        self.context=np.stack(context);self.context.flags.writeable=False
        self.resampled_native_planes=len(planes)
        self.resampled_pixels=len(planes)*(y1-self.y0)*(x1-self.x0)

    def patch(self,job):
        if tuple(job) not in self.jobs:raise ValueError('Tile outside this sampler plan')
        y=int(job[1])-self.y0;x=int(job[2])-self.x0;p=self.config.patch
        return self.context[:,y:y+p,x:x+p]  # Read-only strided view, no tile allocation.


def compile_input(folder,compiler=None):
    folder=Path(folder).resolve();compiler=compiler or shutil.which('g++')
    if not compiler:raise RuntimeError('Local g++ required for fused packing')
    # Keep the ctypes library basename distinct from this Python module:
    # otherwise Linux would import the .so as a Python extension on the next run.
    target=folder/('nodule_input_native.dll' if os.name=='nt' else 'nodule_input_native.so')
    meta=folder/'nodule_input_native_build.json';src=folder/'nodule_fast_input.cpp'
    digest=lambda p:hashlib.sha256(Path(p).read_bytes()).hexdigest()
    command=[str(compiler),'-O3','-std=c++11','-shared']
    command+=['-static-libgcc','-static-libstdc++'] if os.name=='nt' else ['-fPIC']
    if platform.machine().lower() in ('armv7l','armv7'):command+=['-mcpu=cortex-a9','-mfpu=neon']
    command += [str(src),'-o',str(target)]
    if os.name=='nt' and hasattr(os,'add_dll_directory'):
        _DLLS.append(os.add_dll_directory(str(Path(compiler).resolve().parent)))
    if target.exists() or meta.exists():
        d=json.loads(meta.read_text(encoding='utf-8'))
        if d['source_sha256']!=digest(src) or d['binary_sha256']!=digest(target) or d['command']!=command:
            raise ValueError('Native input build changed; use fresh folder')
        return target,d
    env=dict(os.environ);env['PATH']=str(Path(compiler).resolve().parent)+os.pathsep+env.get('PATH','')
    tick=time.perf_counter();p=subprocess.run(command,env=env,text=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    if p.returncode:raise RuntimeError('Native input compilation failed:\n'+p.stdout)
    d=dict(source_sha256=digest(src),binary_sha256=digest(target),command=command,
        build_ms=(time.perf_counter()-tick)*1000,output=p.stdout)
    with meta.open('x',encoding='utf-8') as f:json.dump(d,f,indent=2)
    return target,d


class NativeInput:
    def __init__(self,library):
        self.lib=ctypes.CDLL(str(Path(library).resolve()))
        # LUT is generated by the frozen reference formula, including its exact
        # FP64 tie behavior. Do not replace by a different integer rounding rule.
        a=np.arange(-32768,32768,dtype=np.float64)
        self.lut=np.rint((a.clip(-1000,400)+1000)*(255./1400.)).astype(np.uint8)
        a16=np.ctypeslib.ndpointer(dtype=np.int16);u8=np.ctypeslib.ndpointer(dtype=np.uint8,flags='C_CONTIGUOUS')
        self.lib.nodule_pack.argtypes=[a16,ctypes.c_size_t,ctypes.c_size_t,ctypes.c_size_t,u8,u8,ctypes.c_size_t,ctypes.c_int]
        self.lib.nodule_pack.restype=ctypes.c_int
        self.chw=np.empty((45,64,64),np.uint8)

    def pack(self,patch,destination,hwc8=False):
        patch=np.asarray(patch);out=np.asarray(destination)
        count=64*64*(48 if hwc8 else 45)
        if (patch.dtype!=np.int16 or patch.shape!=(5,128,128) or any(s<=0 or s%2 for s in patch.strides)
                or not out.flags.c_contiguous or not out.flags.writeable or out.nbytes<count
                or out.dtype not in (np.dtype('uint8'),np.dtype('uint64'))
                or np.shares_memory(patch,out)):
            raise ValueError('Need five-plane INT16 view and separate contiguous writable output')
        raw=out.view(np.uint8).reshape(-1)
        result=self.lib.nodule_pack(patch,*(s//2 for s in patch.strides),self.lut,raw,len(raw),int(hwc8))
        if result:raise RuntimeError('Native pack rejected: '+str(result))
        return destination

    def lower(self,patch):
        self.pack(patch,self.chw,False);return self.chw
